export function simulateOfflineTestingRun(scenarioId: string): TestingRunResult {
  const blueprint = THREAT_SCENARIOS.find((s) => s.id === scenarioId) || THREAT_SCENARIOS[0];
  const steps = blueprint.steps.map((s, idx) => ({
    event_id: `sim-${scenarioId}-${idx + 1}`,
    tool_name: s.tool_name,
    tool_server: s.tool_server,
    destination_domain: s.destination_domain || null,
    risk_score: s.composite_score,
    decision: s.decision,
    decision_reason: s.reason,
    risk_factors: s.composite_score >= 0.4 ? [s.reason] : [],
    duration_ms: Number((4.2 + idx * 1.3).toFixed(2)),
    breakdown: {
      rule_score: s.rule_score,
      markov_score: s.markov_score,
      isolation_score: s.isolation_score,
      transformer_score: s.transformer_score,
      composite_score: s.composite_score,
    },
  }));
  const peak = Math.max(...steps.map((s) => s.risk_score), 0);
  const finalDecision = steps.some((s) => s.decision === 'quarantine')
    ? 'quarantine'
    : steps.some((s) => s.decision === 'block')
      ? 'block'
      : steps.some((s) => s.decision === 'flag')
        ? 'flag'
        : 'allow';

  return {
    run_id: `sim-${Date.now().toString(36)}`,
    scenario_id: blueprint.id,
    scenario_name: blueprint.name,
    category: blueprint.category,
    session_id: `sim-session-${blueprint.id}`,
    agent_id: 'sim-agent-01',
    execution_mode: 'offline_simulation',
    executed_at: new Date().toISOString(),
    duration_ms: Number(steps.reduce((acc, s) => acc + s.duration_ms, 0).toFixed(2)),
    peak_risk_score: peak,
    final_decision: finalDecision,
    threats_detected: steps.flatMap((s) => s.risk_factors),
    steps,
  };
}

